    for y in [-.82,.72]:box(back,'light seal edge',(3.3,.042,.035),(1.79,y,.08),'black',.005)
    for y in [-.65,-.27,.11,.49]:cyl(back,'hinge knuckle',.065,.30,(0,y,.005),'edge')
    cyl(back,'hinge pin',.025,1.65,(0,-.05,.005),'silver')
