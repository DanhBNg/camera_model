    cyl(body,'lens release seat',.085,.035,(1.18,-.32,.585),'edge','z')
    cyl(body,'lens release button',.06,.04,(1.18,-.32,.61),'black','z')
    top=group('top',(0,1.015,0))
    box(top,'sculpted top cover',(3.86,.37,1.2),(0,0,0),'silver',.10)
    box(top,'top seam',(3.71,.021,1.09),(0,-.18,0),'black',.03)
    text(top,'brand','A T E L I E R',.12,(.02,.015,.606),'dark')
    text(top,'edition','PRECISION  /  35',.055,(.02,-.095,.606),'dark')
    box(top,'shoe insulating base',(.56,.027,.45),(-.13,.20,-.07),'black')
    box(top,'accessory shoe floor',(.47,.024,.4),(-.13,.224,-.07),'edge')
    for x in [-.38,.12]:box(top,'shoe rail',(.06,.065,.42),(x,.25,-.07),'silver',.012)
    cyl(top,'flash contact',.05,.013,(-.13,.245,-.04),'brass')
    for x in [-1.7,1.7]:screw(top,'top screw',(x,.192,.36),'y',.03)
    base=group('base',(0,-1.035,0))
    box(base,'bottom plate',(3.84,.18,1.2),(0,0,0),'silver',.06)
    box(base,'bottom gasket',(3.68,.02,1.08),(0,.103,0),'black')
    ring(base,'tripod threaded socket',.135,.075,.09,(.15,-.073,0),'brass','y')
    for i in range(4):ring(base,'socket thread',.081,.068,.009,(.15,-.045-i*.015,0),'edge','y')
    cyl(base,'base latch',.23,.025,(-1.25,-.106,0),'edge')
    box(base,'latch slot',(.27,.012,.035),(-1.25,-.122,0),'black')
