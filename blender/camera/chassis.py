    body=group('body')
    front_shell(body)
    for n,sz,pos in [('left wall',(.15,1.82,1.03),(-1.83,-.04,0)),('right wall',(.15,1.82,1.03),(1.83,-.04,0)),('floor',(3.6,.12,1.03),(0,-.91,0))]:box(body,n,sz,pos,r=.05)
